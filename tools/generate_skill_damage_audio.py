"""Snapshot skill audio classifications from the paired server DB; never builds.

Requires PyYAML. Follows the server's skill DB imports, including import overrides.
The generated data is only a legacy fallback: extended damage packets carry the
resolved property, range, and damage kind used by the actual attack.
"""
import argparse
from pathlib import Path
import re

import yaml


def read_database(server, name):
    entries = {}

    def read(path):
        if not path.is_file():
            return
        data = yaml.safe_load(path.read_text(encoding="utf-8-sig")) or {}
        for entry in data.get("Body", []):
            entries.setdefault(entry["Id"], {}).update(entry)
        for entry in data.get("Footer", {}).get("Imports", []):
            if entry.get("Mode", "Renewal") == "Renewal":
                read(server / entry["Path"])

    read(server / "db/re" / name)
    read(server / "db/import" / name)
    return entries


def generate(server):
    return render_skill_damage_audio(read_database(server, "skill_db.yml"))


def render_weapon_damage_audio(items):
    weapons = dict(Dagger=1, **{"1hSword": 2, "2hSword": 3, "1hSpear": 4, "2hSpear": 5,
                               "1hAxe": 6, "2hAxe": 7, "Mace": 8, "2hMace": 9,
                               "Staff": 10, "Bow": 11, "Knuckle": 12, "Musical": 13,
                               "Whip": 14, "Book": 15, "Katar": 16, "2hStaff": 23})
    elements = dict(Neutral=0, Water=1, Earth=2, Fire=3, Wind=4, Poison=5,
                    Holy=6, Dark=7, Ghost=8, Undead=9)
    ranges = []
    for item_id, item in sorted(items.items()):
        weapon = weapons.get(item.get("SubType"), -1)
        if not (item.get("Type") == "Weapon" and weapon >= 0
                or item.get("Type") == "Ammo" and item.get("SubType") == "Arrow"):
            continue
        script = item.get("Script") or ""
        element = 0
        if "bAtkEle" in script:
            # Do not infer a property from a conditional or dynamic item script.
            match = re.fullmatch(r"\s*bonus\s+bAtkEle\s*,\s*Ele_(\w+)\s*;\s*", script)
            element = elements.get(match[1], -1) if match else -1
        if ranges and ranges[-1][1] + 1 == item_id and ranges[-1][2:] == [weapon, element]:
            ranges[-1][1] = item_id
        else:
            ranges.append([item_id, item_id, weapon, element])
    rows = ["// Generated by tools/generate_skill_damage_audio.py from the server item DB.",
            "// { first item ID, last item ID, weapon type (-1 for arrows), element (-1 if dynamic) }."]
    rows.extend(f"    {{ {first}, {last}, {weapon}, {element} }},"
                for first, last, weapon, element in ranges)
    return "\n".join(rows) + "\n"


def render_skill_damage_audio(skills):
    elements = dict(Neutral=0, Water=1, Earth=2, Fire=3, Wind=4, Poison=5,
                    Holy=6, Dark=7, Shadow=7, Ghost=8, Undead=9, Weapon=-1)
    rows = ["// Generated by tools/generate_skill_damage_audio.py from the server skill DB.",
            "// { skill ID, damage kind, element, single impact at every level, long range }."]
    for skill_id, skill in sorted(skills.items()):
        kind = skill.get("Type")
        if kind not in ("Weapon", "Magic", "Misc"):
            continue
        element = skill.get("Element", "Neutral")
        element = elements.get(element, -2) if isinstance(element, str) else -2
        count = skill.get("HitCount", 1)
        if isinstance(count, list):
            count = max(abs(row["Count"]) for row in count)
        distance = skill.get("Range", 1)
        if isinstance(distance, list):
            distance = max(row.get("Size", 1) for row in distance)
        damage_kind = "Magic" if kind == "Magic" else "Physical"
        # HitCount is the count in one damage notification, not the complete
        # spell. Ground/persistent/area spells can send many one-hit packets.
        single_impact = (abs(count) <= 1 and skill.get("TargetType") != "Ground"
                         and not skill.get("Unit") and not skill.get("SplashArea"))
        rows.append(f"    {{ {skill_id}, CombatDamageKind::{damage_kind}, {element}, "
                    f"{str(single_impact).lower()}, {str(distance > 3).lower()} }}, // {skill['Name']}")
    return "\n".join(rows) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--server", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1]
                        / "src/skill/SkillDamageAudio.generated.inc")
    parser.add_argument("--weapon-output", type=Path, default=Path(__file__).resolve().parents[1]
                        / "src/audio/WeaponDamageAudio.generated.inc")
    args = parser.parse_args()
    args.output.write_text(generate(args.server), encoding="utf-8")
    args.weapon_output.write_text(render_weapon_damage_audio(read_database(args.server, "item_db.yml")),
                                  encoding="utf-8")
